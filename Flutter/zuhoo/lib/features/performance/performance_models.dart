/// The nine competencies a review scores, in the order the form asks for them.
///
/// Each is 1–10 on the DTO. The annotations are never actually enforced —
/// neither the create nor the update endpoint carries `@Valid` — so the range
/// is the form's job, not the server's.
const reviewCompetencies = <({String key, String label})>[
  (key: 'scoreWorkQuality', label: 'Quality of work'),
  (key: 'scoreProductivity', label: 'Productivity'),
  (key: 'scoreCommunication', label: 'Communication'),
  (key: 'scoreTeamwork', label: 'Teamwork'),
  (key: 'scoreInitiative', label: 'Initiative'),
  (key: 'scorePunctuality', label: 'Punctuality'),
  (key: 'scoreLeadership', label: 'Leadership'),
  (key: 'scoreProblemSolving', label: 'Problem solving'),
  (key: 'scoreInnovation', label: 'Innovation'),
];

/// POST /hr/performance and PATCH /hr/performance/{id}
///
/// One class for both, because the backend uses one DTO for both.
///
/// The update path is a **true sparse patch** — every field is null-checked
/// before it is assigned, with no unguarded exceptions — so an omitted key
/// genuinely means "leave it alone". That is unusual in this codebase and
/// worth stating, because the neighbouring candidate and opportunity endpoints
/// behave the opposite way.
///
/// `employeeId` and the review period are only meaningful on create; the
/// update path ignores all three, so the edit form does not offer them.
///
/// `overallScore` is never sent: the service averages whichever competencies
/// are present, skipping nulls, and recomputes it on every write.
///
/// Deliberately absent: `goals`, which the DTO takes as a JSON array string
/// for the goal-tracking bars. Composing JSON by hand is not a phone task, and
/// omitting it leaves whatever the web app set.
class PerformanceReviewRequest {
  const PerformanceReviewRequest({
    this.employeeId,
    this.reviewPeriodStart,
    this.reviewPeriodEnd,
    this.scores = const {},
    this.strengths,
    this.areasForImprovement,
    this.goalsForNextPeriod,
    this.comments,
    this.performanceLevel,
    this.promotionRecommendation,
    this.trainingRecommendation,
    this.recognition,
    this.goalCompletionPercent,
  });

  final int? employeeId;
  final String? reviewPeriodStart;
  final String? reviewPeriodEnd;

  /// Keyed by the DTO's own field names — see [reviewCompetencies].
  final Map<String, int?> scores;

  final String? strengths;
  final String? areasForImprovement;
  final String? goalsForNextPeriod;
  final String? comments;
  final String? performanceLevel;
  final String? promotionRecommendation;
  final String? trainingRecommendation;
  final String? recognition;
  final int? goalCompletionPercent;

  factory PerformanceReviewRequest.from(PerformanceReview review) =>
      PerformanceReviewRequest(
        scores: {
          'scoreWorkQuality': review.scoreWorkQuality,
          'scoreProductivity': review.scoreProductivity,
          'scoreCommunication': review.scoreCommunication,
          'scoreTeamwork': review.scoreTeamwork,
          'scoreInitiative': review.scoreInitiative,
          'scorePunctuality': review.scorePunctuality,
          'scoreLeadership': review.scoreLeadership,
          'scoreProblemSolving': review.scoreProblemSolving,
          'scoreInnovation': review.scoreInnovation,
        },
        strengths: review.strengths,
        areasForImprovement: review.areasForImprovement,
        goalsForNextPeriod: review.goalsForNextPeriod,
        comments: review.comments,
        performanceLevel: review.performanceLevel,
        promotionRecommendation: review.promotionRecommendation,
        trainingRecommendation: review.trainingRecommendation,
        recognition: review.recognition,
        goalCompletionPercent: review.goalCompletionPercent,
      );

  Map<String, dynamic> toJson() {
    String? clean(String? value) {
      final trimmed = value?.trim();
      return (trimmed == null || trimmed.isEmpty) ? null : trimmed;
    }

    return {
      if (employeeId != null) 'employeeId': employeeId,
      if (reviewPeriodStart != null) 'reviewPeriodStart': reviewPeriodStart,
      if (reviewPeriodEnd != null) 'reviewPeriodEnd': reviewPeriodEnd,
      // An unscored competency is left out rather than sent as null, so on an
      // edit it keeps whatever it already had instead of being cleared.
      for (final entry in scores.entries)
        if (entry.value != null) entry.key: entry.value,
      if (clean(strengths) != null) 'strengths': clean(strengths),
      if (clean(areasForImprovement) != null)
        'areasForImprovement': clean(areasForImprovement),
      if (clean(goalsForNextPeriod) != null)
        'goalsForNextPeriod': clean(goalsForNextPeriod),
      if (clean(comments) != null) 'comments': clean(comments),
      if (clean(performanceLevel) != null)
        'performanceLevel': clean(performanceLevel),
      if (clean(promotionRecommendation) != null)
        'promotionRecommendation': clean(promotionRecommendation),
      if (clean(trainingRecommendation) != null)
        'trainingRecommendation': clean(trainingRecommendation),
      if (clean(recognition) != null) 'recognition': clean(recognition),
      if (goalCompletionPercent != null)
        'goalCompletionPercent': goalCompletionPercent,
    };
  }
}


