  final String? performanceLevel;
  final String? promotionRecommendation;
  final String? promotionReadiness;
  final String? trainingRecommendation;
  final String? recognition;
  final int? goalCompletionPercent;

  /// Generated by the AI module. Labelled as such wherever it is shown — a
  /// machine's summary of somebody's year should never be mistaken for their
  /// manager's words.
  final String? aiSummary;

  final String? createdAt;

  /// Who signed off which stage and when — stamped by `POST /{id}/advance`
  /// for the stage it just moved *past*, so [selfAssessmentAt] is only ever
  /// set once the review has left [PerformanceStage.selfAssessment], and so
  /// on. Absent entirely for a stage the review has not yet cleared.
  final String? selfAssessmentAt;
  final String? selfAssessmentBy;
  final String? managerReviewAt;
  final String? managerReviewBy;
  final String? hrApprovalAt;
  final String? hrApprovalBy;
  final String? finalApprovalAt;
  final String? finalApprovalBy;

  /// Every stage transition this review has actually recorded, oldest first
  /// — the audit trail the detail screen renders as a timeline. A stage with
  /// no timestamp yet (including the one currently in progress) is omitted
  /// rather than shown as a blank entry.
  List<({String stage, String? at, String? by})> get stageHistory => [
        (
          stage: PerformanceStage.selfAssessment,
          at: selfAssessmentAt,
          by: selfAssessmentBy,
        ),
        (
          stage: PerformanceStage.managerReview,
          at: managerReviewAt,
          by: managerReviewBy,
        ),
        (
          stage: PerformanceStage.hrApproval,
          at: hrApprovalAt,
          by: hrApprovalBy,
        ),
        (
          stage: PerformanceStage.finalApproval,
          at: finalApprovalAt,
          by: finalApprovalBy,
        ),
      ].where((s) => s.at != null).toList(growable: false);

  String get personLabel => employeeName?.trim().isNotEmpty == true
      ? employeeName!.trim()
      : 'Employee #${employeeId ?? id}';

  String get stageLabel =>
      PerformanceStage.labels[stage] ?? stage.replaceAll('_', ' ');

  int get stageIndex {
    final i = PerformanceStage.ordered.indexOf(stage);
    return i < 0 ? 0 : i;
  }

  bool get isComplete => stage == PerformanceStage.completed;

  /// A finalised review is a signed record. Nothing can move it on, and the
  /// screen must not offer to.
  bool get canAdvance => !finalised && !isComplete;

  /// Only a review that has reached the end can be signed off.
  bool get canFinalise => !finalised && isComplete;

  String? get period {
    final start = reviewPeriodStart;
    final end = reviewPeriodEnd;
    if (start == null && end == null) return null;
    return '${start ?? '?'} → ${end ?? '?'}';
  }

  /// The nine scored dimensions, in the order the form asks for them. Every
  /// one is optional, so the detail screen shows only those that were filled.
  List<ReviewScore> get scores => [
        ReviewScore('Work quality', scoreWorkQuality),
        ReviewScore('Productivity', scoreProductivity),
        ReviewScore('Communication', scoreCommunication),
        ReviewScore('Teamwork', scoreTeamwork),
        ReviewScore('Initiative', scoreInitiative),
        ReviewScore('Punctuality', scorePunctuality),
        ReviewScore('Leadership', scoreLeadership),
        ReviewScore('Problem solving', scoreProblemSolving),
        ReviewScore('Innovation', scoreInnovation),
      ];

  List<ReviewScore> get filledScores =>
      scores.where((s) => s.value != null).toList(growable: false);

  bool get hasScores => filledScores.isNotEmpty;

  /// The written half. Empty strings are treated as absent so a blank section
  /// never renders as a heading with nothing under it.
  List<({String title, String body})> get narrative {
    final sections = <({String title, String? body})>[
      (title: 'Strengths', body: strengths),
      (title: 'Areas to improve', body: areasForImprovement),
      (title: 'Goals for next period', body: goalsForNextPeriod),
      (title: 'Training suggested', body: trainingRecommendation),
      (title: 'Recognition', body: recognition),
      (title: 'Comments', body: comments),
    ];
    return [
      for (final s in sections)
        if (s.body?.trim().isNotEmpty == true)
          (title: s.title, body: s.body!.trim()),
    ];
  }

  factory PerformanceReview.fromJson(Map<String, dynamic> json) =>
      PerformanceReview(
        id: (json['id'] as num?)?.toInt() ?? 0,
        stage: json['stage'] as String? ?? PerformanceStage.selfAssessment,
        finalised: json['finalised'] as bool? ?? false,
        employeeId: (json['employeeId'] as num?)?.toInt(),
        employeeName: json['employeeName'] as String?,
        reviewedByName: json['reviewedByName'] as String?,
        reviewPeriodStart: json['reviewPeriodStart'] as String?,
        reviewPeriodEnd: json['reviewPeriodEnd'] as String?,
        overallScore: (json['overallScore'] as num?)?.toDouble(),
        scoreWorkQuality: (json['scoreWorkQuality'] as num?)?.toInt(),
        scoreProductivity: (json['scoreProductivity'] as num?)?.toInt(),
        scoreCommunication: (json['scoreCommunication'] as num?)?.toInt(),
        scoreTeamwork: (json['scoreTeamwork'] as num?)?.toInt(),
        scoreInitiative: (json['scoreInitiative'] as num?)?.toInt(),
        scorePunctuality: (json['scorePunctuality'] as num?)?.toInt(),
        scoreLeadership: (json['scoreLeadership'] as num?)?.toInt(),
        scoreProblemSolving: (json['scoreProblemSolving'] as num?)?.toInt(),
        scoreInnovation: (json['scoreInnovation'] as num?)?.toInt(),
        strengths: json['strengths'] as String?,
        areasForImprovement: json['areasForImprovement'] as String?,
        goalsForNextPeriod: json['goalsForNextPeriod'] as String?,
